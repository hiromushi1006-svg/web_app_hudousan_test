import { Link } from 'react-router-dom'
// 期日アラートを何日前から出すかの設定（説明文に使う）
import { ALERT_DAYS } from '../lib/alerts'
// ソフトの工程とプロジェクトのフェーズの定義（説明文に一覧を出すため）
